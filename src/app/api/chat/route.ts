function normalize(text: string): string {
  return text
    .replace(/[\u200c\u200f\u200e]/g, ' ')
    .replace(/[ي]/g, 'ی')
    .replace(/[ك]/g, 'ک')
    .replace(/[أإآ]/g, 'ا')
    .replace(/[ؤ]/g, 'و')
    .replace(/[ة]/g, 'ه')
    .replace(/[۰-۹]/g, (d) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d)))
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

/** POST /api/chat { message } → { reply, suggestions } */
export async function POST(req: NextRequest) {
  try {
    const body = await req.json().catch(() => ({}));
    const message = String(body.message || '').slice(0, 500);
    if (!message.trim()) {
      return NextResponse.json({ error: 'پیام خالی است' }, { status: 400 });
    }
    const norm = normalize(message);

    let best: Entry | null = null;
    let bestScore = 0;
    for (const entry of KB) {
      let score = 0;
      for (const key of entry.keys) {
        const nk = normalize(key);
        if (norm.includes(nk)) score += nk.length;
      }
      if (score > bestScore) {
        bestScore = score;
        best = entry;
      }
    }

    // Small artificial delay removed — keep response instant
    if (best) {
      return NextResponse.json({ reply: best.answer, suggestions: best.suggest || [] });
    }
    return NextResponse.json({ reply: DEFAULT_ANSWER, suggestions: DEFAULT_SUGGESTIONS });
  } catch (e) {
    console.error('POST /api/chat error', e);
    return NextResponse.json(
      { reply: 'خطایی رخ داد؛ لطفا دوباره تلاش کنید یا با ۱۴۹۸ تماس بگیرید.', suggestions: [] },
      { status: 500 }
    );
  }
}
